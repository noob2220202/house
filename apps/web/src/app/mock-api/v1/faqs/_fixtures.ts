/**
 * FAQ (admin module: GET /faqs). Mirrors the Prisma `Faq` model (category, question, answer,
 * sortOrder). Answers are plain text with light markup ("- " bullets, "1. " lists).
 */
export interface MockFaq {
  id: string;
  category: FaqCategory;
  question: string;
  answer: string;
  sortOrder: number;
}

