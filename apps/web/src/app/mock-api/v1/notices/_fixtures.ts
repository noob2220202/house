/** Pinned first, then newest first — the public list order. */
export function sortedNotices(): MockNotice[] {
  return [...NOTICES].sort(
    (a, b) =>
      Number(b.isPinned) - Number(a.isPinned) ||
      Date.parse(b.publishedAt) - Date.parse(a.publishedAt),
  );
}
