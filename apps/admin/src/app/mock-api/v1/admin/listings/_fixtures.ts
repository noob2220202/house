/** Appends a history entry (newest first) and bumps `updatedAt`. */
export function addListingHistory(
  l: AdminListingDetail,
  entry: Omit<ListingHistoryEntry, 'id' | 'createdAt'>,
): void {
  const createdAt = new Date().toISOString();
  l.history.unshift({
    id: mid('b6', 900_000 + l.history.length + (Date.now() % 10_000)),
    createdAt,
    ...entry,
  });
  l.updatedAt = createdAt;
}

/** Hide a listing (also used when a report is resolved with LISTING_HIDDEN). */
export function hideListing(l: AdminListingDetail, reason: string, adminName: string): void {
  l.status = 'HIDDEN';
  l.hiddenReason = reason;
  addListingHistory(l, {
    action: 'LISTING_HIDDEN',
    actorType: 'ADMIN',
    actorName: adminName,
    note: reason,
  });
}
