#!/usr/bin/env node
// Generates React sources from the approved design snippets (design/drafts/system/snippets.html):
//   src/icons/paths.generated.tsx      – 24-grid stroke icon set
//   src/icons/category.generated.tsx   – category line icons (one cobalt detail)
//   src/art/photos.generated.tsx       – photo stand-ins (branded placeholders)
//   src/art/SuncheonMapArt.generated.tsx – stylized Suncheon base map
// Run: pnpm --filter @house/ui gen   (output is committed; re-run only when the design changes)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const src = fs.readFileSync(path.resolve(root, '../../design/drafts/system/snippets.html'), 'utf8');

const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
function toJsx(svgInner) {
  if (/\sstyle=/.test(svgInner)) throw new Error('inline style in svg art is not supported');
  return svgInner
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\sclass=/g, ' className=')
    .replace(/\s([a-z]+(?:-[a-z]+)+)=/g, (m, name) =>
      name.startsWith('aria-') || name.startsWith('data-') ? m : ` ${camel(name)}=`,
    )
    .trim();
}
const header = (what) =>
  `// GENERATED by packages/ui/scripts/gen-from-design.mjs from design/drafts/system/snippets.html — do not edit.\n// ${what}\n`;

// ---- icons ----
const icons = [...src.matchAll(/<!-- icon: ([\w-]+) -->\s*<svg[^>]*>([\s\S]*?)<\/svg>/g)].map(
  (m) => [m[1], toJsx(m[2])],
);
if (icons.length < 40) throw new Error(`expected 40+ icons, got ${icons.length}`);
fs.writeFileSync(
  path.join(root, 'src/icons/paths.generated.tsx'),
  `${header('Icon set: 24 grid · stroke 1.75 · currentColor')}import type { ReactNode } from 'react';\n\nexport const GENERATED_ICON_PATHS = {\n${icons
    .map(([n, jsx]) => `  '${n}': (\n    <>\n      ${jsx}\n    </>\n  ),`)
    .join('\n')}\n} satisfies Record<string, ReactNode>;\n`,
);

// ---- category icons ----
const cats = [
  ...src.matchAll(/<!-- cat: (\w+) -->\s*<span class="cat-tile"><svg[^>]*>([\s\S]*?)<\/svg>/g),
].map((m) => [
  m[1],
  toJsx(m[2])
    .replace(/className="cat-acc-f"/g, 'data-accent="fill"')
    .replace(/className="cat-acc"/g, 'data-accent="fill"'),
]);
if (cats.length !== 5) throw new Error(`expected 5 category icons, got ${cats.length}`);
fs.writeFileSync(
  path.join(root, 'src/icons/category.generated.tsx'),
  `${header('Category icons: line icons with one cobalt detail (data-accent)')}import type { ReactNode } from 'react';\n\nexport const GENERATED_CATEGORY_PATHS = {\n${cats
    .map(([n, jsx]) => `  ${n}: (\n    <>\n      ${jsx}\n    </>\n  ),`)
    .join('\n')}\n} satisfies Record<string, ReactNode>;\n`,
);

// ---- photo stand-ins ----
const photos = [
  ...src.matchAll(
    /<!-- photo: (\w+) -->\s*<div[^>]*><svg viewBox="([^"]+)"[^>]*>([\s\S]*?)<\/svg>/g,
  ),
].map((m) => [m[1], m[2], toJsx(m[3])]);
if (photos.length !== 6) throw new Error(`expected 6 photo stand-ins, got ${photos.length}`);
fs.writeFileSync(
  path.join(root, 'src/art/photos.generated.tsx'),
  `${header('Photo stand-ins used as branded placeholders when a listing/agency has no photo')}import type { ReactNode } from 'react';\n\nexport const GENERATED_PHOTO_ART = {\n${photos
    .map(
      ([n, vb, jsx]) =>
        `  ${n}: {\n    viewBox: '${vb}',\n    node: (\n      <>\n        ${jsx}\n      </>\n    ),\n  },`,
    )
    .join('\n')}\n} satisfies Record<string, { viewBox: string; node: ReactNode }>;\n`,
);

// ---- Suncheon base map ----
const mapBlock = src.slice(src.indexOf('SUNCHEON BASE MAP SVG'));
const mm = /<svg class="map-svg" viewBox="([^"]+)"[^>]*>([\s\S]*?)<\/svg>/.exec(mapBlock);
if (!mm) throw new Error('base map svg not found');
// Drop the optional dashed "selected area" polygon — StaticMapView draws selections itself.
const mapInner = mm[2].replace(
  /<path[^>]*stroke="#1D4FF2"[^>]*stroke-dasharray="7 5"[^>]*\/>/g,
  '',
);
fs.writeFileSync(
  path.join(root, 'src/art/SuncheonMapArt.generated.tsx'),
  `${header('Stylized Suncheon base map (muted land, 동천, parks, roads, 전라선, 동 boundaries)')}import type { SVGProps } from 'react';\n\nexport const SUNCHEON_MAP_VIEWBOX = { width: ${mm[1].split(' ')[2]}, height: ${mm[1].split(' ')[3]} } as const;\n\nexport function SuncheonMapArt(props: SVGProps<SVGSVGElement>) {\n  return (\n    <svg viewBox="${mm[1]}" preserveAspectRatio="xMidYMid slice" aria-hidden="true" {...props}>\n      ${toJsx(mapInner)}\n    </svg>\n  );\n}\n`,
);
console.log(`icons ${icons.length}, categories ${cats.length}, photos ${photos.length}, map ok`);
